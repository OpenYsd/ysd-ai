-- 0049 — بصمةُ محتوى الملف: منعُ التكرار عند إعادة اختيار الملفِّ نفسِه
--
-- ★ المشكلة: `client_upload_id` يمنع تكرارَ **الطلب** المعاد فقط. من ظنّ
--   الرفعَ فاشلًا فاختار الملفَّ نفسَه من جديد يحمل معرّفًا جديدًا، فيُنشأ
--   صفٌّ ثانٍ لنفس البايتات. رُصد حيًّا في الإنتاج: ثلاثةُ صفوفٍ لملفٍّ واحد.
--
-- ★ الفحصُ في المسار (قراءة ثمّ كتابة) يضيّق النافذة ولا يغلقها؛ هذا الفهرس
--   يغلقها: طلبان متزامنان بالبايتات نفسِها ⇒ أحدهما 23505 يقرأ صفَّ الرابح.
--
-- ★ لماذا هذا الفهرسُ آمنٌ على بياناتٍ قائمةٍ فيها تكرار:
--     الصفوفُ السابقة لا تحمل `metadata->>'content_sha256'` (NULL)، وشرطُ
--     الفهرس يستثنيها صراحةً. فلا يفشل الإنشاء على التكرار الموجود، ولا
--     يُحذف منه شيء. الإصلاحُ الأثريُّ قرارٌ منفصلٌ بمراجعةٍ منفصلة.
--
-- ★ COALESCE على conversation_id ضرورة: في فهارس Postgres الفريدة
--   NULL <> NULL، فلولاها لما قُيّد شيءٌ من الملفات غير المربوطة بمحادثة.

create unique index if not exists files_content_fingerprint_uniq
  on public.files (
    user_id,
    coalesce(conversation_id, '00000000-0000-0000-0000-000000000000'::uuid),
    (metadata->>'content_sha256'),
    size_bytes
  )
  where deleted_at is null and metadata->>'content_sha256' is not null;

comment on index public.files_content_fingerprint_uniq is
  'بصمةُ بايتات الملف داخل نطاق (المستخدم، المحادثة) — تمنع تكرارَ الصف عند إعادة اختيار الملفِّ نفسِه. تستثني الصفوفَ السابقةَ بلا بصمة.';
