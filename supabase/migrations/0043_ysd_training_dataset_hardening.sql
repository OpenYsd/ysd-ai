-- ملاحظتان رفعهما مستشار Supabase بعد تطبيق `0042`، وتخصّانها وحدها. ولا
-- تمسّ هذه الترحيلة دلالةً واحدة: لا حالات الإصدارات، ولا قيود التجميد،
-- ولا البيان، ولا المرشّحين، ولا الموافقات، ولا خدمة YSD. ومن يقرأ
-- الجدولين بعدها يجدهما كما تركتهما `0042` تمامًا.
--
-- ولا صفَّ يُدخَل، ولا ملء رجعيّ، ولا تعديل عمود، ولا مساس بـ`0042`.

begin;

-- ───────────────────────────────────────────────────────────────────
--  (١) دالّة المِشغَل لا تُستدعى مباشرةً
-- ───────────────────────────────────────────────────────────────────
--
-- ★ لماذا يلزم السحب، والدالّة لا تفعل شيئًا خطيرًا ظاهرًا.
--
-- لأنها `security definer`: تعمل بصلاحية مالكها لا بصلاحية مستدعيها. وهي
-- تقرأ `public.training_dataset_releases` — وهو جدولٌ سُحبت امتيازاته من
-- `anon` و`authenticated` في `0042` عمدًا.
--
-- فبقاء `execute` مفتوحًا يجعلها **نافذةً حول ذلك المنع**: يستدعيها من لا
-- يملك قراءة الجدول، فتقرأ هي عنه. وهي لا تُعيد الصفّ اليوم — لكنها تُفرّق
-- في السلوك بين إصدارٍ موجودٍ مجمَّد (استثناء) وإصدارٍ لا وجود له (صمت).
-- وذلك فرقٌ يُقرأ: قناةٌ جانبية تكشف وجود الصفّ وحالته لمن لا حقّ له فيهما.
--
-- ودالّةٌ لا يُستدعيها إلا المِشغَل لا تحتاج `execute` لأحدٍ من أدوار
-- العميل. فالأصل ألّا يكون الباب مفتوحًا لمن لا يمرّ منه.
--
-- ── ولماذا `revoke` وحده لا تحويلها إلى `invoker` ──
--
-- لأن `security invoker` تغيير **سلوك**: تصير الدالّة تقرأ الإصدارات
-- بصلاحية الكاتب. و`service_role` يملكها فيمرّ؛ لكن أيّ دورٍ آخر يُمنح
-- كتابةً على العناصر يومًا سيسقط مِشغَله بخطأِ صلاحيةٍ غامض بدل أن يحرس.
-- والسحب يُغلق الباب بلا أن يمسّ ما وراءه.
--
-- ── وهل يبقى المِشغَل يعمل؟ ──
--
-- نعم. فـPostgreSQL يفحص `execute` على دالّة المِشغَل عند **إنشائه** لا
-- عند إطلاقه: المنفّذ يناديها من داخله، لا بوصفها استدعاءً من المستخدم.
-- وهذا مُثبَتٌ على PostgreSQL حقيقيّ في `v113-pg-training-datasets`،
-- بدورٍ لا يملك `execute` ويكتب فيُحرَس.
--
-- و`revoke` على امتيازٍ غير ممنوح لا يفشل، فالسطر آمنٌ مهما تكرّر.

revoke execute on function public.guard_frozen_dataset_items() from public;
revoke execute on function public.guard_frozen_dataset_items() from anon;
revoke execute on function public.guard_frozen_dataset_items() from authenticated;

-- ───────────────────────────────────────────────────────────────────
--  (٢) فهرسٌ يغطّي `created_by`
-- ───────────────────────────────────────────────────────────────────
--
-- ★ لماذا يلزم.
--
-- PostgreSQL يُنشئ فهرسًا للمفتاح الأساسيّ وللفرادة، ولا يُنشئ شيئًا للطرف
-- **المُشير** من مرجعٍ خارجيّ. و`created_by` يشير إلى `profiles(id)`، فكل
-- حذفٍ لملفٍّ شخصيّ يفرض مسحًا كاملًا لجدول الإصدارات للتحقّق من
-- `on delete set null`.
--
-- وأثرُه ليس نظريًّا: حذفُ حسابٍ فعلٌ يقع في مسارٍ ينتظره إنسان، ويتتالى
-- عبر جداول كثيرة. فبلا هذا الفهرس يُبطئ سجلُّ إصداراتٍ **لا علاقة له
-- بالحساب** حذفًا لا يخصّه.
--
-- والمرجع نفسه لا يُمسّ: `on delete set null` تبقى — فحذفُ من أنشأ إصدارًا
-- لا يمحو الإصدار. سجلُّ ما جرى يبقى، ويفقد نسبته إلى شخص.

create index if not exists training_dataset_releases_created_by_idx
  on public.training_dataset_releases (created_by);

-- ملاحظة: `0042` تبقى كما هي — لم تُعدَّل ولم يُسقَط منها شيء. وهذه
-- الترحيلة لا تُدخل صفًّا ولا تُغيّر صفًّا ولا تمسّ خدمة YSD.

commit;
