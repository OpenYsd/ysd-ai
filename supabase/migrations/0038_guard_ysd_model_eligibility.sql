-- ═══════════════════════════════════════════════════════════════════
--  0038 — حراسة أهليّة نموذج YSD في القاعدة (v0.9.3، الرقعة التاسعة)
-- ═══════════════════════════════════════════════════════════════════
--
-- ── الالتفاف الذي تغلقه ──
--
-- `admin_set_model_enabled` من 0009 دالةٌ `security definer` يستطيع
-- تنفيذها كل `authenticated`، وتتحقّق داخليًّا من `is_admin()` وحدها.
-- فأي مشرفٍ يقدر أن يستدعيها **مباشرةً** — من عميل Supabase أو من
-- `curl` — ويفعّل أي نموذج بلا مرور بمسار الخادم.
--
-- وذلك مقبولٌ لكل النماذج القائمة: تفعيلها قرار تشغيليّ بسيط. أما نموذج
-- YSD فتفعيلُه يشترط أن نكون قد تحقّقنا من جاهزية وقت التشغيل فعلًا —
-- والقاعدة لا تستطيع أن تفحص شبكةً. فالحلّ أن تُغلق هنا، ويُفتح الباب
-- الوحيد في الخادم حيث يمكن الفحص.
--
-- ── وحارسٌ في التطبيق وحده لا يكفي ──
--
-- لأن الالتفاف لا يمرّ بالتطبيق أصلًا. والحراسة تكون عند المورد لا عند
-- أحد أبوابه.
--
-- ── وما لا تفعله هذه الترحيلة ──
--
-- لا تفعّل شيئًا. `ysd/model-alpha` يبقى `enabled = false` بعدها كما كان
-- قبلها. وهي تحمي المسار فقط — والتفعيل قرارٌ يُتّخذ في الخادم بيد
-- المالك، بعد أن يقول الفحص «متصل».

begin;

-- ───────────────────────────────────────────────────────────────────
--  (١) الدالة: سلوكها القديم حرفيًّا، وباب YSD مغلق
-- ───────────────────────────────────────────────────────────────────
--
-- `create or replace` يُبقي الصلاحيات القائمة، لكنها تُعاد تأكيدًا في (٢)
-- كي لا تعتمد الحراسة على ما لم يُقَل صراحةً.

create or replace function public.admin_set_model_enabled(p_id text, p_enabled boolean)
returns text language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not is_admin() then return 'forbidden'; end if;

  /**
   * ★ تفعيل نموذج YSD لا يمرّ من هنا — ولا للمالك.
   *
   * ولا يُستثنى المالك عمدًا: الاستثناء يجعل الحارس اتفاقًا لا قاعدة،
   * ومن يملك تجاوزه يتجاوزه سهوًا في ليلةٍ متعبة. والمسار الخادميّ
   * مفتوح له، وهو الطريق الذي يفحص الجاهزية قبل الكتابة.
   *
   * والرمز مغلق: `ysd_guarded` يقول «مرفوض هنا» لا «ممنوع عليك» —
   * فالفرق بينهما هو الفرق بين توجيهٍ وبين رفضٍ مبهم.
   */
  if p_id = 'ysd/model-alpha' and p_enabled is true then
    return 'ysd_guarded';
  end if;

  /**
   * ★ والتعطيل يمرّ دائمًا — وهو المقصود.
   *
   * مفتاح إيقافٍ ثانٍ: إغلاق أهليّة القاعدة يوقف الخدمة وإن تعذّر كل
   * شيء آخر. وحارسٌ يمنع الإغلاق في الطوارئ حارسٌ ضدّنا.
   */
  update ai_models set enabled = p_enabled where id = p_id;
  return case when found then 'ok' else 'not_found' end;
end $$;

-- ───────────────────────────────────────────────────────────────────
--  (٢) الصلاحيات — تُعاد تأكيدًا لا تغييرًا
-- ───────────────────────────────────────────────────────────────────
--
-- `authenticated` يبقى قادرًا على التنفيذ لأن الدالة تفحص `is_admin()`
-- داخلها؛ وسحبُه يكسر لوحة الإدارة بلا أن يضيف أمانًا. و`public`
-- و`anon` ممنوعان كما في 0009.

revoke all on function public.admin_set_model_enabled(text, boolean) from public;
revoke all on function public.admin_set_model_enabled(text, boolean) from anon;
grant execute on function public.admin_set_model_enabled(text, boolean) to authenticated;

comment on function public.admin_set_model_enabled(text, boolean) is
  'تفعيل/تعطيل نموذج للمشرفين. تفعيل ysd/model-alpha محجوب هنا (ysd_guarded) '
  'ويمرّ بمسار الخادم الذي يفحص جاهزية وقت التشغيل. وتعطيله مسموح دائمًا.';

-- ملاحظة: لا `update` ولا `insert` في هذه الترحيلة. أهليّة YSD تبقى
-- `false` كما زرعتها 0036 — وهذه تحمي الطريق إليها لا تسلكه.

commit;
