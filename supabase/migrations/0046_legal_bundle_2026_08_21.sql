-- ============================================================
-- 0046 — رفع إصدار الحزمة القانونية: 2026-07-15 → 2026-08-21
--
-- ── لماذا ──
--
-- سياسة الخصوصية تغيّرت جوهريًّا في المرحلة 6A: صارت تُفصح عن المساهمة
-- الاختيارية في تحسين YSD — الإذن، والمشاركة الصريحة، والمراجعة البشرية،
-- والسحب. ومن وافق على نصّ 2026-07-15 وافق على وثيقةٍ لا تذكر شيئًا من ذلك.
--
-- فالإفصاح جاء بعد الجمع، وهذا الترحيل يعيد الترتيب: يُطلب من كل مستخدم
-- قبولٌ صريح للنصّ الذي يذكره.
--
-- ── ما يفعله بالضبط ──
--
-- سطرٌ واحد في `platform_settings`. لا مخطّط، ولا جدول، ولا دالّة.
--
-- ── وقارن-ثمّ-اضبط ──
--
-- الشرط `value = '"2026-07-15"'` جزءٌ من الكتابة نفسها لا قراءةٌ قبلها.
-- فلو كان الإعداد قد رُفع سلفًا — أو رُفع إلى قيمةٍ أخرى بيد أحد — لم
-- يُكتب شيء. وإعادةُ تشغيل الترحيل بلا أثر.
--
-- ── وما لا يمسّه ──
--
-- `user_consents`: لا صفَّ يُعدَّل ولا يُدرَج. الموافقة فعلٌ صريح من صاحبها،
--   وكتابتُها نيابةً عنه تجعل الوثيقة موقّعةً بلا موقّع.
-- `training_consents` و`training_candidates` وكلُّ جداول التدريب: قبولُ
--   الشروط والإذن بالتدريب نظامان منفصلان. ورفعُ إصدارٍ قانونيّ لا يُعيد
--   إذنًا سُحب، ولا يُنشئ مرشّحًا، ولا يستعيد أثرًا مُحي.
-- `allow_registration` و`require_invite` وأي إعدادٍ آخر: لا يُمَسّ.
-- ============================================================

update public.platform_settings
   set value = '"2026-08-21"'::jsonb,
       updated_at = now()
 where key = 'terms_version'
   and value = '"2026-07-15"'::jsonb;

-- تحقّق: الإعداد موجود وبالقيمة المقصودة. وإلا فالبيئة ليست حيث نظنّ.
do $$
declare
  v_current text;
begin
  select value #>> '{}' into v_current
    from public.platform_settings
   where key = 'terms_version';

  if v_current is null then
    raise exception '0046: terms_version setting is missing';
  end if;

  if v_current <> '2026-08-21' then
    raise exception '0046: terms_version is %, expected 2026-08-21', v_current;
  end if;
end $$;
