import { createHash } from "node:crypto";

/**
 * مفاتيح حدّ المعدّل لمسارات الدعوة — **هاش لا قيمة خام**.
 *
 * حدّ المعدّل يحتفظ بمفاتيحه في الذاكرة، وقد تظهر في تفريغ ذاكرة أو تشخيص.
 * كود الدعوة والبريد لا يجوز أن يوجدا هناك بصيغتهما، والهاش يكفي تمامًا:
 * الغرض عدّ المحاولات لا استرجاع القيمة.
 *
 * ولماذا لا يُكتفى بحدّ الـIP: شبكةٌ موزّعة تتجاوزه بلا عناء، وكلٌّ من الكود
 * والبريد هدفٌ قائم بذاته — الأول يُستنزف حتى تُجمَّد الدعوة عند سقف الإصدار،
 * والثاني يُطارَد لإزعاج صاحبه. ثلاثة حدود لثلاثة أهداف مختلفة.
 */

/** هاش مختصر — 32 حرفًا تكفي مفتاحًا وتقلّل حجم الذاكرة */
export function inviteRateKey(value: string): string {
  return createHash("sha256").update(value.trim().toLowerCase()).digest("hex").slice(0, 32);
}
