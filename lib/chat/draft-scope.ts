import "server-only";

/**
 * نطاق مسودة المحادثة الجديدة لكل مستخدم — يُشتقّ على الخادم من هويّته الموثَّقة (المرحلة 3D).
 *
 * المسودة تُحفظ في متصفح المستخدم، والمتصفح قد يتشاركه أكثر من حساب. فمفتاح «محادثة جديدة» يحمل
 * نطاقًا خاصًّا بكل حساب كي لا يجد حسابٌ نصًّا كتبه غيره ولم يرسله. والنطاق بصمةٌ لا المعرّف نفسه:
 * معرّف المستخدم لا يدخل أسماء مفاتيح التخزين ولا حمولة الصفحة.
 *
 * والوسم غير وسم المفضّلة (`favorites-scope.ts`): بصمتان لاستعمالين لا تُربط إحداهما بالأخرى.
 *
 * ليس حدًّا أمنيًّا — التخزين المحليّ يقرؤه كل من يملك المتصفح؛ هو عزلٌ للواجهة بين الحسابات.
 */

import { createHash } from "node:crypto";

/** بادئة ثابتة تفصل هذا الاستعمال عن أي بصمةٍ أخرى للمعرّف نفسه */
const SCOPE_LABEL = "ysd.chatDraft.v1:";

/** بصمةٌ حتمية بـ32 خانةً ستّ عشرية — الحساب نفسه يجد مسودته في كل زيارة */
export function chatDraftScopeFor(userId: string): string {
  return createHash("sha256").update(`${SCOPE_LABEL}${userId}`, "utf8").digest("hex").slice(0, 32);
}
