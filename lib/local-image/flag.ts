/**
 * رايةُ التوليد المحلّيّ للصور — مطفأةٌ ما لم تُشعل صراحةً.
 *
 * ── لماذا رايةٌ أصلًا ──
 *
 * الميزةُ تفتح ثقبًا في سياسة أمن المحتوى (وصلةٌ إلى الحلقة المحلّية).
 * وثقبٌ مفتوحٌ دائمًا لأجل ميزةٍ لا يستعملها أحدٌ بعد هو توسيعٌ لسطح
 * الهجوم بلا مقابل. فتُشعل حيث تُستعمل، وتبقى مطفأةً حيث لا تُستعمل.
 *
 * ── ولماذا ليست سرًّا ──
 *
 * قيمتُها تُقرأ في المتصفّح كي تعرف الواجهةُ أتعرض الميزةَ أم لا، وكلُّ
 * ما يصل المتصفّحَ مكشوف. فجعلُها سرًّا يوهم بحمايةٍ لا وجودَ لها.
 * وهي ليست إذنًا: لا تفتح بابًا إلى بيانات، وإنما تُظهر واجهةً تتّصل
 * بجهاز المستخدم نفسه.
 *
 * ── ومصدرٌ واحد ──
 *
 * ★ تُقرأ من هنا وحدها. فلو قرأت السياسةُ من متغيّرٍ وقرأت الواجهةُ من
 *   آخر، لأمكن أن تَعرض الواجهةُ زرًّا تمنع السياسةُ نداءه — أو أسوأ: أن
 *   تُفتح السياسةُ في بيئةٍ لا واجهةَ فيها تستعملها.
 */

/**
 * المنفذُ المثبَّت للمحرّك المحلّيّ.
 *
 * ★ منفذٌ واحد لا مدى.
 *
 * لو تنقّل المحرّكُ بين المنافذ لاحتاجت السياسةُ `127.0.0.1:*` — وذلك
 * يُصرّح لكلِّ خدمةٍ محلّية على الجهاز، لا لمحرّكنا. فالتثبيتُ هنا شرطُ
 * أن تبقى السياسةُ ضيّقة.
 *
 * وعند التزاحم على المنفذ يمتنع المحرّكُ ويُعلن، ولا يقفز إلى غيره.
 */
export const LOCAL_ENGINE_PORT = 47615;
export const LOCAL_ENGINE_ORIGIN = `http://127.0.0.1:${LOCAL_ENGINE_PORT}`;

/**
 * القيمةُ الحرفيّة التي تُشعل الراية — ولا يكفي وجودُ المتغيّر.
 *
 * فقيمةٌ مثل `"false"` أو `"0"` أو فراغٌ تُبقيها مطفأة. والاكتفاءُ بوجود
 * المتغيّر يجعل `LOCAL_IMAGE=false` يُشعلها — وهو عكسُ ما يقرؤه الناظر.
 */
const ENABLED_VALUE = "1";

/**
 * أمشتعلةٌ هي؟
 *
 * تُقرأ من البيئة العامّة (`NEXT_PUBLIC_`) كي يراها المتصفّحُ والخادمُ
 * بقيمةٍ واحدة. و`process.env.NEXT_PUBLIC_*` يُستبدل وقتَ البناء في حزمة
 * المتصفّح، فيجب أن يُكتب كاملًا لا أن يُركَّب اسمُه من أجزاء.
 */
export function isLocalImageEnabled(env?: Record<string, string | undefined>): boolean {
  /**
   * حين تُحقن البيئةُ صراحةً (في الاختبارات) تُقرأ كما هي.
   */
  if (env) return env.NEXT_PUBLIC_YSD_LOCAL_IMAGE === ENABLED_VALUE;

  /**
   * ★ وإلا فالاسمُ يُكتب **حرفيًّا** — ولا يُقرأ من متغيّرٍ وسيط.
   *
   * حزمةُ المتصفّح لا تحوي `process.env`؛ وإنما يستبدل المُجمِّعُ النصَّ
   * `process.env.NEXT_PUBLIC_XXX` بقيمته وقتَ البناء. والاستبدالُ يقع على
   * **الشكل الحرفيّ** وحده.
   *
   * وقد كتبتُ أوّلًا `env = process.env` في وسيطٍ افتراضيّ ثم قرأتُ
   * `env.NEXT_PUBLIC_...`، فلم يجد المُجمِّعُ شكلًا يستبدله. فصارت الرايةُ
   * تشتعل في الخادم وتنطفئ في المتصفّح: السياسةُ تفتح الحلقةَ المحلّية،
   * وصفحةُ الإعدادات تُصيَّر على الخادم — واللوحةُ لا تظهر في المحادثة أبدًا.
   *
   * وأسوأُ ما فيه أنّ تحذيرَ هذا بعينه مكتوبٌ في رأس هذا الملفّ، ثم خُولف.
   */
  return process.env.NEXT_PUBLIC_YSD_LOCAL_IMAGE === ENABLED_VALUE;
}

/** اسمُ المتغيّر — يُذكر في الوثائق والاختبارات بلا تكرارِ الحرف */
export const LOCAL_IMAGE_ENV_VAR = "NEXT_PUBLIC_YSD_LOCAL_IMAGE";
