/**
 * بوّابةُ التصريف — حدٌّ لعدد تصريفات RAG المتزامنة في العمليّة الواحدة.
 *
 * ★ لماذا
 *
 *   التضمين يعمل داخل العمليّة (`@huggingface/transformers`)، ونموذجُه وحدَه
 *   يرفع الذاكرة من ~0.1 إلى ~0.45 GB. وحدُّ بيئة التجربة 512 MB. وكان كلُّ
 *   طلب `POST /api/files/:id/rag` يشغّل تصريفَه الخاصّ؛ فرفعُ عدّة مستنداتٍ معًا
 *   يعني عدّة تصريفاتٍ متوازية (تنزيلٌ واستخراجٌ وتقسيمٌ لكلٍّ منها فوق النموذج)
 *   — فتتجاوز الحدّ وتُعاد العمليّة، وتبقى الوظائف «تعمل» بنبضٍ متوقّف.
 *   رُصد ذلك حيًّا على التجربة بمقاييس Railway (قفزةٌ إلى ~0.5 GB ثم هبوطٌ
 *   إلى ~0.1 = إعادة تشغيل) في كلّ جولة رفعٍ متعدّد.
 *
 * ★ ما تفعله
 *
 *   تصريفٌ واحدٌ في آنٍ واحد. والطلبُ الذي يجد البوّابةَ مشغولة **لا ينتظر ولا
 *   يُسقط شيئًا**: وظيفتُه أُدرجت قبلها في `rag_jobs` (مصدر الحقيقة)، فيعود
 *   فورًا بـ«في الطابور». والتصريفُ الجاري يلتقط وظائف المستخدم نفسه بعد وظيفته
 *   (`claim_rag_job` يأخذ الأقدم المتاح)، وما بقي يحرّكه طلبٌ لاحق — ومنه
 *   استطلاعُ الواجهة حين يرى وظيفةً مستحقّةً لم يلتقطها أحد.
 *
 * ★ وحدودها
 *
 *   العدّاد في ذاكرة العمليّة: نسخةٌ واحدة من الخدمة ⇒ حدٌّ واحدٌ صحيح. ولو
 *   تعدّدت النسخ صار الحدُّ لكلّ نسخة — وذلك أيضًا حدٌّ للذاكرة، وهي لكلّ نسخة.
 *   وإعادةُ تشغيل العمليّة تُصفّره، ووظائفُها المقطوعة يستعيدها عقدُ الإيجار
 *   (`LEASE_SECONDS`) كما كان.
 */

/** تصريفٌ واحد في آنٍ واحد — التضمين محلّيٌّ وهامشُ الذاكرة ضيّق */
export const MAX_CONCURRENT_DRAINS = 1;

let active = 0;

/** يحجز مكانًا إن وُجد؛ ويعيد دالّةَ تحريرٍ آمنةً للتكرار، أو `null` إن كانت البوّابة ممتلئة */
export function tryAcquireDrainSlot(): (() => void) | null {
  if (active >= MAX_CONCURRENT_DRAINS) return null;
  active += 1;
  let released = false;
  return () => {
    if (released) return;
    released = true;
    active -= 1;
  };
}

/** عدد التصريفات الجارية الآن — للقياس والاختبار */
export function activeDrainCount(): number {
  return active;
}
