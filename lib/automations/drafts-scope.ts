import "server-only";

/**
 * نطاق مسودات سير العمل لكل مستخدم — يُشتقّ على الخادم من هويّته الموثَّقة (المرحلة 4A).
 *
 * المسودات تُحفظ في متصفح المستخدم، والمتصفح قد يتشاركه أكثر من حساب. فالمفتاح يحمل نطاقًا خاصًّا
 * بكل حساب كي لا يرى حسابٌ مسودات غيره. والنطاق بصمةٌ لا المعرّف نفسه، بوسمٍ غير وسمَي المفضّلة
 * ومسودة المحادثة: ثلاث بصماتٍ لثلاثة استعمالات لا تُربط إحداها بالأخرى.
 *
 * ليس حدًّا أمنيًّا — التخزين المحليّ يقرؤه كل من يملك المتصفح؛ هو عزلٌ للواجهة بين الحسابات.
 */

import { createHash } from "node:crypto";

/** بادئة ثابتة تفصل هذا الاستعمال عن أي بصمةٍ أخرى للمعرّف نفسه */
const SCOPE_LABEL = "ysd.automationDrafts.v1:";

/** بصمةٌ حتمية بـ32 خانةً ستّ عشرية — الحساب نفسه يجد مسوداته في كل زيارة */
export function automationDraftsScopeFor(userId: string): string {
  return createHash("sha256").update(`${SCOPE_LABEL}${userId}`, "utf8").digest("hex").slice(0, 32);
}
