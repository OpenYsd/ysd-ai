/**
 * ★ الاسمُ يُكتب حرفيًّا، والقيمةُ تُطابَق حرفيًّا.
 *
 * هي رايةُ الصوت نفسُها — لا رايةٌ ثانية. ولا يُقرأ الاسمُ من متغيّرٍ وسيط
 * ولا يُركَّب من أجزاء: `NEXT_PUBLIC_*` يستبدلها المُجمِّعُ بالنصّ، فما لم
 * يجد الشكلَ الحرفيَّ لم يستبدل شيئًا.
 *
 * والقيمةُ `"1"` وحدَها. فـ`"true"` و`"yes"` تُقرأ «مشتعلة» عينًا وهي
 * مطفأةٌ حكمًا — واختلافُ ما يراه الناظرُ عمّا ينفّذه الكود هو بذرةُ العطب.
 */
const ENABLED_VALUE = "1";

/** يُقاس ما تراه هذه الوحدة، ويُحقن في الاختبار بلا تلويثِ بيئةِ العملية */
export function isVoiceOn(env) {
  const source = env ?? process.env;
  return source.NEXT_PUBLIC_YSD_LOCAL_VOICE === ENABLED_VALUE;
}

/**
 * تُبنى القيمةُ من قِطَعٍ ثابتة — والميكروفونُ وحدَه يتبدّل.
 *
 * ★ الترتيبُ ثابت والصياغةُ ثابتة: فحصُ الإطفاء يطابق النصَّ الحاليَّ
 * حرفًا بحرف، وأيُّ إعادةِ ترتيبٍ «تجميليّة» تكسره — وهو المقصود.
 */
export function buildPermissionsPolicy(env) {
  const microphone = isVoiceOn(env) ? "(self)" : "()";
  return `camera=(), microphone=${microphone}, geolocation=()`;
}

/** ما لا يُفتح البتّة — يُذكر ليُقاس، لا ليُقرأ */
export const NEVER_ENABLED = Object.freeze([
  "camera",
  "geolocation",
  "display-capture",
  "usb",
  "serial",
  "bluetooth",
  "midi",
  "payment",
  "hid",
]);
