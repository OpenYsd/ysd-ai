import "server-only";

/**
 * نطاق المفضّلة لكل مستخدم — يُشتقّ على الخادم من هويّته الموثَّقة (المرحلة 3C).
 *
 * المفضّلة تُحفظ في متصفح المستخدم، والمتصفح قد يتشاركه أكثر من حساب. فالمفتاح يحمل نطاقًا
 * خاصًّا بكل حساب كي لا يرى حسابٌ مفضّلة غيره بعد تبديل الدخول. والنطاق بصمةٌ لا المعرّف
 * نفسه: معرّف المستخدم لا يدخل أسماء مفاتيح التخزين ولا حمولة الصفحة.
 *
 * ليس حدًّا أمنيًّا — التخزين المحليّ يقرؤه كل من يملك المتصفح؛ هو عزلٌ للواجهة بين الحسابات،
 * والمحفوظ معرّفات مهاراتٍ مدمجة عامّة لا أكثر.
 */

import { createHash } from "node:crypto";

/** بادئة ثابتة تفصل هذا الاستعمال عن أي بصمةٍ أخرى للمعرّف نفسه */
const SCOPE_LABEL = "ysd.skillFavorites.v1:";

/** بصمةٌ حتمية بـ32 خانةً ستّ عشرية — الحساب نفسه يجد مفضّلته في كل زيارة */
export function favoritesScopeFor(userId: string): string {
  return createHash("sha256").update(`${SCOPE_LABEL}${userId}`, "utf8").digest("hex").slice(0, 32);
}
