/**
 * أيُّ صوتٍ يعمل في هذا البناء؟ — قرارٌ واحد، يُحسم مرّةً عند تحميل الوحدة.
 *
 * ══════════════════════════════════════════════════════════════════
 *  ★ صوتان لا يجتمعان
 *
 *  «الصوتُ المحلّيّ» (المحرّكُ على الجهاز، خلف رايته) ينطق كلَّ ردٍّ مكتمل
 *  من تلقاء نفسه، ويعرض تحت الميكروفون أنّ الصوت يُعالج على الجهاز.
 *  و«استمع» (قراءةُ الرد بصوت المتصفّح، خلف رايةٍ أخرى) تقرأ بضغطة، وقد
 *  يكون صوتُها عبر الشبكة بعد موافقة المستخدم.
 *
 *  فلو عملا في بناءٍ واحد: لتكلّم صوتان معًا، ولتجاورت مجموعتا أزرارٍ لا
 *  يوقف زرُّ إحداهما الأخرى، ولصار السطرُ الذي يقول إنّ الصوت يُعالج على
 *  الجهاز معروضًا بجوار قراءةٍ قد تغادره.
 *
 *  ★ والصوتُ المحلّيّ يتقدّم
 *
 *  إن اشتعلت رايتُه غابت «استمع» كلُّها — زرًّا وسؤالًا وإفصاحًا — وبقي هو
 *  كما كان حرفًا بحرف: لا يُمسّ من شيفرته ولا من أسلاكه شيء. والحسمُ هنا،
 *  خارج وحداته، فلا تعرف هي عن هذه الراية شيئًا.
 *
 *  ★ ولماذا ثابتٌ لا دالّة
 *
 *  مُحقِّقُ الصوت المحلّيّ ينفّذ كلَّ دالّةٍ صغيرة يجد فيها اسمَ رايته في
 *  الحزمة المشحونة، ويشترط أن تُعيد قيمةَ الراية. فدالّةٌ هنا تنادي قارئَ
 *  تلك الراية مع شيءٍ آخر قد تُضمَّن فيها العبارةُ عند التصغير، فتُعدّ
 *  «بوّابةً» ثانية وتُسقط البوّابة. فالقرارُ ثابتُ وحدة، والدالّةُ المحضة
 *  أدناه لا تقرأ رايةً: تأخذ قيمتين وتُعيد قيمة.
 *
 *  ★ ولا شيءَ يُلمس عند التحميل
 *
 *  لا نافذةَ ولا تخزينَ ولا مستمع: نداءان لقارئَي الرايتين، وحسب.
 * ══════════════════════════════════════════════════════════════════
 */
import { isBrowserVoiceEnabled } from "@/lib/browser-voice/flag";
import { isLocalVoiceEnabled } from "@/lib/local-voice/flag";

/**
 * أتُعرض «استمع»؟ — دالّةٌ محضة على قيمتين، لجدول الحقيقة.
 *
 * رايةُ صوت المتصفّح مشتعلة **و**رايةُ الصوت المحلّيّ مطفأة. وما سوى ذلك لا.
 */
export function resolveReadAloud(flags: { browserVoice: boolean; localVoice: boolean }): boolean {
  return flags.browserVoice && !flags.localVoice;
}

const browserVoice = isBrowserVoiceEnabled();
const localVoice = isLocalVoiceEnabled();

/** القرارُ لهذا البناء — يقرؤه صفُّ الرد، وزرُّ «استمع»، وصفحةُ الخصوصيّة */
export const READ_ALOUD_AVAILABLE: boolean = resolveReadAloud({ browserVoice, localVoice });
