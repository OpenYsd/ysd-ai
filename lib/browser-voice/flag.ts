/**
 * ★ `"1"` حرفيًّا وحدها تُشعل.
 *
 * فقيمةٌ مثل `"false"` أو `"0"` أو فراغٌ تُبقيها مطفأة. والاكتفاءُ بوجود
 * المتغيّر يجعل `BROWSER_VOICE=false` يُشعلها — وهو عكسُ ما يقرؤه الناظر.
 */
const ENABLED_VALUE = "1";

/** اسمُ المتغيّر — يُذكر في الوثائق والاختبارات بلا تكرارِ الحرف */
export const BROWSER_VOICE_ENV_VAR = "NEXT_PUBLIC_YSD_BROWSER_VOICE";

/**
 * أمشتعلةٌ هي؟
 *
 * @param env بيئةٌ تُحقن صراحةً في الاختبارات؛ وبغيابها يُقرأ الشكلُ الحرفيّ.
 */
export function isBrowserVoiceEnabled(env?: Record<string, string | undefined>): boolean {
  if (env) return env.NEXT_PUBLIC_YSD_BROWSER_VOICE === ENABLED_VALUE;
  return process.env.NEXT_PUBLIC_YSD_BROWSER_VOICE === ENABLED_VALUE;
}
