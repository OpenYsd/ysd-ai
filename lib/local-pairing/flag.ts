/**
 * رايةُ الاقتران الدائم بالمحرّك المحلّيّ — مطفأةٌ ما لم تُشعل صراحةً.
 *
 * ── ولماذا رايةٌ مستقلّةٌ عن الصوت والصورة ──
 *
 * ★ الاقترانُ قدرةٌ قائمةٌ بذاتها، لا زينةٌ على ميزةٍ أخرى.
 *
 * لو رُبط بـ`NEXT_PUBLIC_YSD_LOCAL_VOICE` لصار إشعالُ الصوت يفتح واجهةَ
 * اقترانٍ لم يطلبها أحد، وإطفاؤه يقطع اقترانًا قائمًا تستعمله الصورة.
 * وأسوأُ من ذلك: من أراد الاقترانَ وحدَه لاضطُرّ إلى إشعال الميكروفون
 * معه — وهو توسيعُ أذونٍ بلا سبب.
 *
 * فلكلِّ قدرةٍ رايتُها، ولكلِّ رايةٍ ما تفتحه بالضبط ولا شيءَ سواه.
 *
 * ── وما تفتحه هذه ──
 *
 * وصلةً في `connect-src` إلى عنوان المحرّك، وواجهةَ اقترانٍ في الإعدادات.
 * ولا تفتح ميكروفونًا، ولا توليدَ صورة، ولا تُغيّر سلوكَ الإنتاج القائم.
 *
 * ── وليست سرًّا ──
 *
 * قيمتُها تُقرأ في المتصفّح كي تعرف الواجهةُ أتعرض الميزةَ أم لا. وكلُّ ما
 * يصل المتصفّحَ مكشوف. وهي ليست إذنًا: لا تفتح بابًا إلى بياناتٍ، وإنما
 * تُظهر واجهةً تتّصل بجهاز المستخدم نفسه.
 */

export { LOCAL_ENGINE_ORIGIN, LOCAL_ENGINE_PORT } from "@/lib/local-engine/endpoint";

/**
 * القيمةُ الحرفيّة التي تُشعل الراية — ولا يكفي وجودُ المتغيّر.
 *
 * فقيمةٌ مثل `"false"` أو `"0"` أو فراغٌ تُبقيها مطفأة. والاكتفاءُ بوجود
 * المتغيّر يجعل `...PAIRING=false` يُشعلها — وهو عكسُ ما يقرؤه الناظر.
 */
const ENABLED_VALUE = "1";

/**
 * أمشتعلةٌ هي؟
 *
 * ★ والاسمُ يُكتب **حرفيًّا** — ولا يُقرأ من متغيّرٍ وسيط.
 *
 *   حزمةُ المتصفّح لا تحوي `process.env`؛ وإنما يستبدل المُجمِّعُ النصَّ
 *   `process.env.NEXT_PUBLIC_XXX` بقيمته وقتَ البناء، والاستبدالُ يقع على
 *   **الشكل الحرفيّ** وحده.
 *
 *   وقد وقع هذا العطبُ بعينه في رايةِ الصورة: كُتب `env = process.env`
 *   وسيطًا افتراضيًّا ثم قُرئ منه، فلم يجد المُجمِّعُ شكلًا يستبدله —
 *   فاشتعلت الرايةُ في الخادم وانطفأت في المتصفّح. والسياسةُ تفتح
 *   الحلقةَ المحلّية والواجهةُ لا تظهر أبدًا.
 */
export function isLocalPairingEnabled(env?: Record<string, string | undefined>): boolean {
  /** حين تُحقن البيئةُ صراحةً (في الاختبارات) تُقرأ كما هي */
  if (env) return env.NEXT_PUBLIC_YSD_LOCAL_PAIRING === ENABLED_VALUE;
  return process.env.NEXT_PUBLIC_YSD_LOCAL_PAIRING === ENABLED_VALUE;
}

/** اسمُ المتغيّر — يُذكر في الوثائق والاختبارات بلا تكرارِ الحرف */
export const LOCAL_PAIRING_ENV_VAR = "NEXT_PUBLIC_YSD_LOCAL_PAIRING";

/**
 * نسخةُ بروتوكول الاقتران التي يفهمها هذا العميل.
 *
 * ★ ويُقارَن بـ`pairingApiVersion` من `/version` قبل أيّ خطوة.
 *
 *   وغيابُ الحقل يعني محرّكًا أقدمَ من الاقتران — لا محرّكًا معطوبًا.
 *   والفرقُ يهمّ: الأوّلُ يُعالَج بتحديث المحرّك، والثاني بإصلاحه.
 */
export const SUPPORTED_PAIRING_API_VERSION = 1;
