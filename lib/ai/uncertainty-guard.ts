/**
 * حارس عدم اليقين (v0.6.5 RC2) — يمنع تمرير تفاصيل متخصصة غير مؤكدة.
 *
 * المشكلة: النماذج المجانية تُخمّن أحيانًا مواقع/خطوات/أسماء عناصر دقيقة ثم
 * تُغلّفها بعبارات تحفّظ («بعض المصادر»، «على الأغلب») — فيبدو الرد محتاطًا لكنه
 * يمرّر معلومة قد تكون خاطئة. الحل: إذا اجتمع (١) سؤال يطلب تفاصيل دقيقة و(٢)
 * تحفّظ في الرد و(٣) تفاصيل محددة فعلية → امنع الرد. الموجّه يعيد التوليد مرة
 * بصرامة، وإن أصرّ النموذج تُعرض رسالة عدم تأكّد آمنة بدل التخمين.
 *
 * لا يعتمد على `@/` ليبقى قابلًا للاستيراد في اختبارات vitest.
 */

/** عبارات التحفّظ/عدم اليقين (تشمل ما نصّ عليه المتطلّب) */
const HEDGE_PATTERNS: RegExp[] = [
  /لست\s+متأكد/, // لست متأكدًا
  /قد\s+أكون\s+مخطئ/,
  /ربما/,
  /قد\s+يكون/,
  /أعتقد/,
  /أظن/,
  /بعض\s+المصادر/,
  /على\s+الأغلب/,
  /غالبًا|غالباً/,
];

/** السؤال يطلب مكانًا أو خطوات أو اسم عنصر أو رقمًا دقيقًا */
const SPECIFIC_REQUEST_PATTERNS: RegExp[] = [
  /كيف\s+(?:أ|ن|ت)?(?:حصل|جيب|صل|وصل|أصل|لعب|فتح|أفتح)/, // كيف أحصل/أجيب/أصل…
  /من\s+أين/,
  /أين\s+(?:أجد|يوجد|يقع|أحصل|توجد)/,
  /(?:^|\s)(?:وين|فين)(?:\s|؟|\?|$)/, // مستقلة — لا داخل «تكوين»/«تدوين»
  /الموقع|المكان|الإحداثيات|الخريطة/,
  /الخطوات|خطوات|طريقة\s+الوصول|طريقة\s+الحصول/,
  /ما\s+(?:اسم|هو\s+اسم)|اسم\s+(?:العنصر|السلاح|القطعة|المكان|الشخصية|الوحش)/,
  /كم\s+(?:عدد|يبلغ|تبلغ|سعر|مقدار|نسبة)|النسبة\s+الدقيقة|الرقم\s+الدقيق/,
];

/**
 * الرد يحتوي تفاصيل محددة فعلية — مؤشرات **عامة** لا أنماطًا مفصّلة على مثال بعينه:
 * خطوات مرقّمة، أسماء بين علامات اقتباس، أفعال توجيه/موقع/منطقة/اتجاهات، وأرقام ونسب ومدد.
 */
export function hasSpecificDetails(reply: string): boolean {
  const stripped = reply
    .replace(/```[\s\S]*?(```|$)/g, " ")
    .replace(/`[^`\n]*`/g, " ");
  const patterns: RegExp[] = [
    /^\s*\d+[.)]\s+\S/m, // خطوات مرقّمة
    /«[^»]{2,}»|"[^"]{2,}"|“[^”]{2,}”/, // اسم بين علامات اقتباس
    /اذهب|اتجه|اتّجه|توجه|توجّه|انتقل/, // أفعال توجيه
    /موقع|منطقة/, // موقع أو منطقة
    /(?:^|\s)عند(?:\s|$)/, // «عند» مستقلة (لا «عندما»/«عندك»)
    /شمال|جنوب|شرق|غرب/, // اتجاهات
    /\d/, // أرقام ونسب ومدد
  ];
  return patterns.some((re) => re.test(stripped));
}

/** هل السؤال من نوع يطلب تفاصيل دقيقة؟ */
export function questionWantsSpecifics(userText: string): boolean {
  return SPECIFIC_REQUEST_PATTERNS.some((re) => re.test(userText));
}

/** هل الرد يحمل تحفّظًا صريحًا؟ */
export function replyIsHedged(reply: string): boolean {
  return HEDGE_PATTERNS.some((re) => re.test(reply));
}

/**
 * المخالفة = سؤال يطلب تفاصيل دقيقة + تحفّظ في الرد + تفاصيل محددة فعلية.
 * تحفّظ **بلا** تفاصيل (اعتراف آمن بعدم المعرفة) لا يُعدّ مخالفة — بل هو المطلوب.
 */
export function violatesUncertainty(
  userText: string,
  reply: string,
): { violated: boolean; reason?: string } {
  if (!questionWantsSpecifics(userText)) return { violated: false };
  if (!replyIsHedged(reply)) return { violated: false };
  if (!hasSpecificDetails(reply)) return { violated: false };
  return { violated: true, reason: "uncertain_specifics" };
}

/**
 * هل يحتاج هذا السؤال **الوضع المحمي** (تجميع الرد وفحصه قبل عرضه)؟
 * نعم للأسئلة المتخصصة التي يؤدي اختلاقها إلى جواب خاطئ واضح: موقع عنصر أو مكان،
 * خطوات دقيقة، أسماء أو أرقام أو نسب. وما عداها (كتابة إبداعية، سؤال بسيط، محادثة
 * يومية، تلخيص وشرح عام) يبقى على البثّ الفوري بلا أي تأخير.
 */
export function needsVerifiedMode(userText: string): boolean {
  return questionWantsSpecifics(userText);
}

