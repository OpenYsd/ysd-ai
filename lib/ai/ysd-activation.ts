import "server-only";

/**
 * مفتاح إيقاف الخدمة العامّة لنموذج YSD (v0.9.3، الرقعة الثامنة).
 *
 * ── لماذا مفتاحٌ منفصل عن كل ما سبق ──
 *
 * `YSD_PROVIDER_ENABLED` يقول «البنية التحتية مهيّأة»، و`healthCheck` يقول
 * «وقت التشغيل يحمل النموذج فعلًا». وكلاهما سؤالٌ عن **القدرة**، لا عن
 * **الإذن**. وحين لا يفصل النظام بينهما تصير كل ترقيةِ بنيةٍ تحريرًا
 * غير مقصود: تُصلح إعدادًا فينفتح النموذج للناس بلا قرار.
 *
 * فهذا المفتاح هو الإذن وحده. لا يُهيّئ شيئًا ولا يفحص شيئًا — يسمح فقط.
 *
 * ── والفصل يخدم التسلسل التشغيليّ ──
 *
 *   ١) يُنشر الكود والمفتاح مغلق.
 *   ٢) تُهيّأ القاعدة ووقت التشغيل.
 *   ٣) يُضغط «اختبار الاتصال» حتى يقول «متصل».
 *   ٤) **وبعدها وحدها** يُفتح المفتاح.
 *
 * فالفحص يعمل والمفتاح مغلق — وذلك مقصود: لا يُفتح لأحد ما لم يُثبت أنه
 * يعمل، ولا يُفتح لمجرد أنه صار يعمل.
 *
 * ── وعقد التراجع الطارئ ──
 *
 * إعادته إلى `0` أو حذفه توقف **كل توليدٍ جديد** عبر مزوّد YSD فورًا:
 * لا يظهر النموذج، ولا يُوجَّه إليه طلب، ولا يبدأ بثٌّ مباشر — وإن بقيت
 * القاعدة مفعِّلةً والنشرة نشطةً ووقت التشغيل حيًّا. متغيّر بيئةٍ واحد
 * أسرع من ترحيلةٍ وأقلّ خطرًا من نشرةٍ عاجلة.
 *
 * ولا `NEXT_PUBLIC_`: قرار خدمةٍ يُتّخذ في الخادم، وقيمةٌ في حزمة
 * المتصفّح تُقرأ ولا تُنفَّذ — فتوهم بحراسةٍ ليست هناك.
 */

/**
 * ★ `"1"` وحدها تفتح — تطابقٌ تامّ لا تفسير.
 *
 * `Boolean(env.X)` كان سيجعل `"0"` و`"false"` و`"off"` كلها تفتح الخدمة،
 * لأنها نصوصٌ غير فارغة. وذلك أسوأ ما يمكن أن يحدث لمفتاح إيقاف: يُكتب
 * `0` ظنًّا أنه إغلاق، فيفتح. والصرامة هنا ليست تشدّدًا — هي أن يعني
 * الإغلاقُ إغلاقًا.
 *
 * ولا `trim()`: ` 1` بمسافةٍ خطأٌ مطبعيّ، وقبولُه يعني أن المشغّل لا يعرف
 * بالضبط ما كتبه. والالتباس في مفتاح الطوارئ أخطر من الرفض.
 *
 * والبيئة **تُحقن**: يُختبر المفتاح كاملًا بلا العبث بحالة العملية.
 */
export function isYSDAlphaActivationEnabled(
  env: NodeJS.ProcessEnv = process.env,
): boolean {
  return env.YSD_MODEL_ALPHA_ENABLED === "1";
}

/**
 * ★ أربع بوّاباتٍ مستقلّة تفصل بين «ممكن» و«مسموح».
 *
 * وكلها يجب أن تُفتح معًا كي يصل النموذج إلى مستخدم:
 *
 *   ١) البنية التحتية — `YSD_PROVIDER_ENABLED=1` مع إعداد وقت تشغيلٍ
 *      صالح وصلاحية سجلّ. تقول: نستطيع الاتصال.
 *
 *   ٢) إذن الخدمة — `YSD_MODEL_ALPHA_ENABLED=1`. يقول: نأذن بالخدمة.
 *      وهو ما يضيفه هذا الملفّ.
 *
 *   ٣) أهليّة القاعدة — `ai_models['ysd/model-alpha'].enabled = true`.
 *      ما تزال `false` في `0036`، ولا تُغيَّر في هذه الرقعة.
 *
 *   ٤) قائمة السماح — `ai.allowed_models` إن كانت مفعّلة.
 *
 * والاستقلال هو المقصود: لا بوّابة تفتح أخرى، ولا إحداها تكفي وحدها.
 * فمن فتح واحدةً بالخطأ لم يفتح الخدمة.
 *
 * وجاهزية وقت التشغيل ليست بوّابة خامسة: شرطٌ تشغيليّ يُفحص **قبل** فتح
 * المفتاح، لا في كل طلب. وجعلُه بوّابةً يعني رحلة شبكةٍ في مسار كل
 * محادثة — ثمنٌ يدفعه كل مستخدم لأجل سؤالٍ يُسأل مرةً عند النشر.
 */
