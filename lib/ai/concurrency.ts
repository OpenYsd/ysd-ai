import "server-only";

/**
 * طلب توليد واحد متزامن للخطة المجانية (v0.8.1).
 *
 * ── لماذا ──
 *
 * حدّ الرسائل شهري ويومي، ولا شيء يمنع فتح عشرين لسانًا وإرسال عشرين طلبًا
 * في اللحظة نفسها. كلٌّ منها يحجز اتصالًا بالمزوّد ويستهلك رموزًا، والحدّ
 * اليومي لا يوقفه إلا **بعد** أن تقع الكلفة. الحدّ المتزامن يوقفها قبلها.
 *
 * ── حدود هذا الحارس، صراحةً ──
 *
 * الحالة **في الذاكرة**، فالحدّ لكل نسخة خادم لا للمنصّة كلها. مع نسخة واحدة
 * (وهو وضعنا على Railway) يطابق ذلك المطلوب تمامًا. ومع عدة نسخ يصير الحدّ
 * «واحدًا لكل نسخة» — أضعف من المطلوب لكنه ليس ثغرة: الحدّ اليومي والشهري
 * يبقيان في القاعدة، وهما الحاجز الصلب. الترقية إلى حارس مشترك تحتاج تخزينًا
 * مشتركًا، ولا معنى لدفع ثمنه قبل أن توجد نسخة ثانية.
 *
 * ولا يُستعمل للخطط المدفوعة: من يدفع لا يُحاصَر بطلب واحد.
 */

const active = new Set<string>();

export interface Slot {
  /** يُستدعى في `finally` — آمن للتكرار */
  release: () => void;
}

/** لا حارس: يُعيد قفلًا فارغًا كي يبقى المستدعي بلا تفريع */
const FREE_PASS: Slot = { release: () => {} };

/**
 * يحاول حجز المقعد الوحيد للمستخدم.
 * `null` تعني أن له طلبًا جاريًا بالفعل.
 */
export function acquireGenerationSlot(userId: string, tier: string): Slot | null {
  if (tier !== "free") return FREE_PASS;

  if (active.has(userId)) return null;
  active.add(userId);

  /**
   * `released` يحمي من إطلاقٍ مزدوج: مسار البثّ يمرّ بـ`finally` متداخلة،
   * وإطلاقٌ ثانٍ كان سيحرّر مقعد طلبٍ **لاحق** لنفس المستخدم فيسمح باثنين.
   */
  let released = false;
  return {
    release: () => {
      if (released) return;
      released = true;
      active.delete(userId);
    },
  };
}

/** للاختبارات فقط — يُسقط الحالة بين الحالات */
export function _resetGenerationSlots(): void {
  active.clear();
}

/** للتشخيص: عدد الطلبات الجارية (بلا كشف أي معرّف) */
export function activeGenerationCount(): number {
  return active.size;
}
