import { describe, expect, it } from "vitest";
import { SYSTEM_PROMPT } from "../lib/ai/prompt";

describe("الموجّه — الأسلوب الذي أعجب المختبِر (يبقى)", () => {
  it("إجابة مباشرة أولًا ثم التفاصيل", () => {
    expect(SYSTEM_PROMPT).toMatch(/الإجابة المباشرة أولًا/);
  });
  it("عربي طبيعي بلا وعظ ولا اعتذارات طويلة", () => {
    expect(SYSTEM_PROMPT).toMatch(/عربي طبيعي/);
    expect(SYSTEM_PROMPT).toMatch(/لا وعظ ولا اعتذارات/);
  });
});

describe("السلامة مع فهم السياق — يمنع الرفض الخاطئ", () => {
  it("★ يأمر بفهم السياق كاملًا قبل أي رفض", () => {
    expect(SYSTEM_PROMPT).toMatch(/افهم سياق السؤال كاملًا قبل أي رفض/);
  });

  it("★ الكلمة ليست سببًا للرفض — السياق هو الفيصل", () => {
    expect(SYSTEM_PROMPT).toMatch(/الكلمة ليست سببًا للرفض/);
    expect(SYSTEM_PROMPT).toMatch(/السياق هو الفيصل/);
  });

  it("★ يذكر الكلمات الحساسة الأربع كأمثلة سياق آمن", () => {
    for (const w of ["ضرر", "نزف", "سلاح", "قتل"]) {
      expect(SYSTEM_PROMPT).toContain(w);
    }
  });

  it("★ ألعاب الفيديو وميكانيكياتها تُجاب مباشرة بلا تحذير", () => {
    expect(SYSTEM_PROMPT).toMatch(/ميكانيكيات الألعاب/);
    expect(SYSTEM_PROMPT).toMatch(/أجبها مباشرة بلا أي تحذير/);
  });

  it("★ القصص والروايات والخيال تُجاب بشكل طبيعي", () => {
    expect(SYSTEM_PROMPT).toMatch(/قصة أو رواية أو سيناريو خيالي/);
  });

  it("★ الرفض محصور بالأذى الحقيقي القابل للتطبيق", () => {
    expect(SYSTEM_PROMPT).toMatch(/إيذاء شخص حقيقي/);
    expect(SYSTEM_PROMPT).toMatch(/قابلة للتطبيق في\s*\n?\s*الواقع/);
  });

  it("★ عند غموض السياق: سؤال توضيح واحد بدل الرفض", () => {
    expect(SYSTEM_PROMPT).toMatch(/سؤال توضيح واحد/);
    expect(SYSTEM_PROMPT).toMatch(/بدل الرفض/);
  });
});

describe("الدقة — يمنع الاختلاق", () => {
  it("★ لا يخترع اسم عنصر أو مكان أو رقمًا عند عدم التأكد", () => {
    expect(SYSTEM_PROMPT).toMatch(/لا تخترع اسم عنصر أو مكان أو شخصية أو رقمًا/);
  });

  it("★ يصرّح «لست متأكدًا» بدل التخمين بثقة", () => {
    expect(SYSTEM_PROMPT).toMatch(/لست متأكدًا/);
    expect(SYSTEM_PROMPT).toMatch(/بدل التخمين بثقة/);
  });

  it("★ يفرّق بين المعلومة المؤكدة والتقدير/الاحتمال", () => {
    expect(SYSTEM_PROMPT).toMatch(/المعلومة المؤكدة والتقدير أو الاحتمال/);
  });

  it("★ لا مصادر أو مراجع أو روابط وهمية", () => {
    expect(SYSTEM_PROMPT).toMatch(/لا تذكر مصادر أو مراجع أو روابط وهمية/);
  });

  it("★ الأسئلة المتخصصة: لا خلط بين ألعاب/منتجات متشابهة ولا إحالة عشوائية", () => {
    expect(SYSTEM_PROMPT).toMatch(/لا تخلط بين الألعاب أو المنتجات المتشابهة/);
    expect(SYSTEM_PROMPT).toMatch(/لعبة أو منتج آخر مشابه/);
    expect(SYSTEM_PROMPT).toMatch(/احتمالات عشوائية/);
  });

  it("★ الصيغة المختصرة للاعتراف بعدم التأكد من الخطوات", () => {
    expect(SYSTEM_PROMPT).toMatch(/لست متأكدًا من الخطوات الدقيقة/);
    expect(SYSTEM_PROMPT).toMatch(/بلا\s*\n?\s*اعتذار طويل ولا وعظ/);
  });
});

describe("سيناريوهات المختبِر — التوجيه يغطّيها (بنيويًا)", () => {
  // كل سيناريو يجب أن يجد في الموجّه ما يوجّه سلوكه الصحيح.
  const scenarios: [string, RegExp][] = [
    // سؤال Elden Ring / White Mask: لعبة → إجابة مباشرة بلا تحذير
    ["سؤال لعبة (White Mask في Elden Ring)", /ميكانيكيات الألعاب.*أجبها مباشرة/s],
    // وصف معركة في قصة خيالية
    ["معركة داخل قصة خيالية", /قصة أو رواية أو سيناريو خيالي/],
    // طلب حقيقي لإيذاء شخص → مرفوض
    ["طلب إيذاء حقيقي", /ارفض فقط.*إيذاء شخص حقيقي/s],
    // سؤال ناقص السياق → توضيح
    ["سياق غامض", /غامضًا حقًا.*سؤال توضيح واحد/s],
    // معلومة غير مؤكدة → لا اختلاق
    ["معلومة غير مؤكدة", /لست متأكدًا|لا تخترع/],
  ];
  it.each(scenarios)("%s — موجَّه", (_name, re) => {
    expect(SYSTEM_PROMPT).toMatch(re);
  });
});
